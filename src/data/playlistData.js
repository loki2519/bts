// Helper to look up verified song metadata by song title
export const findSongByTitle = (title) => {
  if (!title) return null;
  const clean = title.toLowerCase().trim().replace(/[:\-_()[\]]/g, ' ').replace(/\s+/g, ' ');
  const allTracks = [...PRIORITY_PLAYLIST, ...SECONDARY_GROUP_PLAYLIST, ...SOLO_MEMBER_PLAYLIST];
  
  // Exact match first
  const exact = allTracks.find(t => t.title.toLowerCase().trim() === clean || t.title.toLowerCase().trim() === title.toLowerCase().trim());
  if (exact) return exact;

  // Normalized word match
  return allTracks.find(t => {
    const tClean = t.title.toLowerCase().trim().replace(/[:\-_()[\]]/g, ' ').replace(/\s+/g, ' ');
    return tClean.includes(clean) || clean.includes(tClean);
  });
};
